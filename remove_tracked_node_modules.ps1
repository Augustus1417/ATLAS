$ErrorActionPreference = 'Stop'
$tracked = & git ls-files
$nodePaths = $tracked | Where-Object { $_ -match 'node_modules' } | ForEach-Object { ($_ -split 'node_modules')[0] + 'node_modules' } | Sort-Object -Unique
if ($nodePaths.Count -eq 0) { Write-Host 'No tracked node_modules found.'; exit 0 }
foreach ($p in $nodePaths) {
  Write-Host "Removing tracked: $p"
  & git rm -r --cached --ignore-unmatch -- "$p"
}
& git add .gitignore
& git commit -m "chore: remove tracked node_modules and update .gitignore"
